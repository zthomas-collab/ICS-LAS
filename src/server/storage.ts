import { mkdir, readFile, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";

/**
 * Object storage boundary.
 *  - Development: local filesystem (./.data/uploads).
 *  - Production: any S3-compatible private bucket (AWS S3, Cloudflare R2, Backblaze B2, MinIO...),
 *    configured with S3_BUCKET, S3_REGION, optional S3_ENDPOINT and the standard AWS credential variables.
 *    The bucket must block public access; objects are only ever served through authorization-checked routes.
 * The local store refuses to run in production unless explicitly allowed.
 */
export interface ObjectStore {
  put(key: string, bytes: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Buffer | null>;
  delete(key: string): Promise<void>;
}

/** Keys are generated by the server only: `<area>/<uuid>.<ext>`. Anything else is refused. */
export const KEY_RE = /^[a-z0-9-]+\/[0-9a-f-]{36}\.(webp|pdf)$/;

export class LocalObjectStore implements ObjectStore {
  constructor(private readonly root: string) {}

  private resolve(key: string): string {
    if (!KEY_RE.test(key)) throw new Error("invalid storage key");
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error("invalid storage key");
    return full;
  }

  async put(key: string, bytes: Buffer): Promise<void> {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, bytes, { flag: "wx" });
  }

  async get(key: string): Promise<Buffer | null> {
    try {
      return await readFile(this.resolve(key));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw err;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }
}

/** The subset of S3Client we use, so tests can supply a fake. */
export type S3Like = { send(command: unknown): Promise<unknown> };

export class S3ObjectStore implements ObjectStore {
  constructor(
    private readonly client: S3Like,
    private readonly bucket: string,
    private readonly prefix = "",
  ) {}

  private key(key: string): string {
    if (!KEY_RE.test(key)) throw new Error("invalid storage key");
    return `${this.prefix}${key}`;
  }

  async put(key: string, bytes: Buffer, contentType: string): Promise<void> {
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: this.key(key),
        Body: bytes,
        ContentType: contentType,
        ServerSideEncryption: "AES256",
        CacheControl: "private, no-store",
        // Never overwrite: keys are random UUIDs, so a collision would indicate a bug or an attack.
        IfNoneMatch: "*",
      }),
    );
  }

  async get(key: string): Promise<Buffer | null> {
    try {
      const out = (await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: this.key(key) }))) as {
        Body?: { transformToByteArray(): Promise<Uint8Array> };
      };
      if (!out.Body) return null;
      return Buffer.from(await out.Body.transformToByteArray());
    } catch (err) {
      const e = err as { name?: string; $metadata?: { httpStatusCode?: number } };
      if (e.name === "NoSuchKey" || e.$metadata?.httpStatusCode === 404) return null;
      throw err;
    }
  }

  async delete(key: string): Promise<void> {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: this.key(key) }));
  }
}

export function createObjectStore(env: Record<string, string | undefined> = process.env): ObjectStore {
  if (env.S3_BUCKET) {
    const client = new S3Client({
      region: env.S3_REGION ?? "us-east-1",
      endpoint: env.S3_ENDPOINT || undefined,
      forcePathStyle: Boolean(env.S3_ENDPOINT),
    });
    return new S3ObjectStore(client, env.S3_BUCKET, env.S3_PREFIX ?? "");
  }
  if (env.NODE_ENV === "production" && env.ALLOW_LOCAL_OBJECT_STORE !== "true") {
    throw new Error("Configure S3_BUCKET (private, S3-compatible object storage) for production; the local store is development-only.");
  }
  const root = env.UPLOADS_DIR ?? path.join(/* turbopackIgnore: true */ process.cwd(), ".data", "uploads");
  return new LocalObjectStore(root);
}

const globalForStore = globalThis as unknown as { __icsStore?: ObjectStore };

export function getObjectStore(): ObjectStore {
  if (!globalForStore.__icsStore) globalForStore.__icsStore = createObjectStore();
  return globalForStore.__icsStore;
}
